CREATE TABLE categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    description text NOT NULL,
    active smallint NOT NULL CHECK (active IN (0,1))
);
CREATE UNIQUE INDEX categories_name_ci ON categories (lower(name));

CREATE TABLE content (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind text NOT NULL CHECK (kind IN ('KUDO','REPLY')),
    author_id bigint NOT NULL REFERENCES accounts(id),
    recipient_id bigint REFERENCES accounts(id),
    category_id bigint REFERENCES categories(id),
    category_name text,
    category_description text,
    root_id bigint REFERENCES content(id),
    parent_id bigint REFERENCES content(id),
    body text NOT NULL CHECK (length(body) > 0),
    created_at text NOT NULL,
    state text NOT NULL CHECK (state IN ('CREATED','VISIBLE','REPORTED','IN_REVIEW','VETOED')),
    CHECK (
        (kind = 'KUDO' AND recipient_id IS NOT NULL AND author_id <> recipient_id AND category_id IS NOT NULL
            AND category_name IS NOT NULL AND category_description IS NOT NULL
            AND root_id IS NULL AND parent_id IS NULL)
        OR
        (kind = 'REPLY' AND recipient_id IS NULL AND category_id IS NULL
            AND category_name IS NULL AND category_description IS NULL
            AND root_id IS NOT NULL AND parent_id IS NOT NULL)
    ),
    CHECK (parent_id IS NULL OR parent_id < id)
);
CREATE FUNCTION check_reply_conversation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.kind = 'REPLY' AND NOT EXISTS (
        SELECT 1 FROM content p WHERE p.id = NEW.parent_id AND coalesce(p.root_id, p.id) = NEW.root_id
    ) THEN
        RAISE EXCEPTION 'invalid reply parent' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER same_conversation BEFORE INSERT ON content
    FOR EACH ROW EXECUTE FUNCTION check_reply_conversation();

CREATE FUNCTION reject_thread_update() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'immutable thread' USING ERRCODE = '23514';
END;
$$;
CREATE TRIGGER immutable_thread BEFORE UPDATE OF root_id, parent_id, kind ON content
    FOR EACH ROW EXECUTE FUNCTION reject_thread_update();

CREATE INDEX thread_by_root ON content (root_id, id);
CREATE INDEX children_by_parent ON content (parent_id, id);
CREATE INDEX kudos_sent ON content (author_id, id) WHERE kind = 'KUDO';
CREATE INDEX kudos_received ON content (recipient_id, id) WHERE kind = 'KUDO';

CREATE TABLE ratings (
    content_id bigint NOT NULL REFERENCES content(id),
    account_id bigint NOT NULL REFERENCES accounts(id),
    stars smallint NOT NULL CHECK (stars BETWEEN 1 AND 5),
    created_at text NOT NULL,
    updated_at text NOT NULL,
    PRIMARY KEY (content_id, account_id)
);

CREATE TABLE reports (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_id bigint NOT NULL REFERENCES content(id),
    reporter_id bigint NOT NULL REFERENCES accounts(id),
    reason text NOT NULL,
    detail text NOT NULL,
    state text NOT NULL CHECK (state IN ('PENDING','IN_REVIEW','ACCEPTED','REJECTED')),
    created_at text NOT NULL,
    reviewed_by bigint REFERENCES accounts(id),
    decided_by bigint REFERENCES accounts(id),
    reviewed_at text,
    decided_at text,
    decision_reason text
);
CREATE UNIQUE INDEX one_open_report ON reports (content_id, reporter_id)
    WHERE state IN ('PENDING','IN_REVIEW');
CREATE INDEX reports_by_content ON reports (content_id, state);

CREATE TABLE vetos (
    content_id bigint PRIMARY KEY REFERENCES content(id),
    moderator_id bigint NOT NULL REFERENCES accounts(id),
    moderator_role text NOT NULL CHECK (moderator_role IN ('RECTOR','ACADEMIC')),
    report_id bigint REFERENCES reports(id),
    reason text NOT NULL,
    created_at text NOT NULL
);

CREATE TABLE audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event text NOT NULL,
    actor_id bigint REFERENCES accounts(id),
    subject text NOT NULL,
    subject_id bigint NOT NULL,
    occurred_at text NOT NULL,
    facts text NOT NULL
);
CREATE INDEX audit_by_actor ON audit (actor_id, id);

CREATE FUNCTION reject_audit_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'audit is append-only' USING ERRCODE = '23514';
END;
$$;
CREATE TRIGGER audit_immutable BEFORE UPDATE OR DELETE OR TRUNCATE ON audit
    FOR EACH STATEMENT EXECUTE FUNCTION reject_audit_change();

