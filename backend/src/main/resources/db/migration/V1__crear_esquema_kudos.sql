CREATE TABLE faculties (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    created_at text NOT NULL
);
CREATE UNIQUE INDEX faculties_name_ci ON faculties (lower(name));

CREATE TABLE programs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_id bigint NOT NULL REFERENCES faculties(id),
    name text NOT NULL,
    created_at text NOT NULL
);
CREATE UNIQUE INDEX programs_faculty_name_ci ON programs (faculty_id, lower(name));

CREATE TABLE accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    email text NOT NULL UNIQUE,
    phone text NOT NULL UNIQUE,
    password_hash text NOT NULL,
    role text NOT NULL CHECK (role IN ('ADMIN','RECTOR','ACADEMIC','FACULTY','PROGRAM','TEACHER','STUDENT')),
    faculty_id bigint REFERENCES faculties(id),
    program_id bigint REFERENCES programs(id),
    status text NOT NULL CHECK (status IN ('PENDING','APPROVED','ACTIVE','SUSPENDED','DEACTIVATED')),
    email_verified smallint NOT NULL DEFAULT 0 CHECK (email_verified IN (0,1)),
    phone_verified smallint NOT NULL DEFAULT 0 CHECK (phone_verified IN (0,1)),
    approved_by bigint REFERENCES accounts(id),
    approved_at text,
    created_at text NOT NULL,
    CHECK ((role = 'FACULTY') = (faculty_id IS NOT NULL)),
    CHECK ((role = 'PROGRAM') = (program_id IS NOT NULL)),
    CHECK (status <> 'ACTIVE' OR (email_verified = 1 AND phone_verified = 1 AND approved_at IS NOT NULL))
);
CREATE UNIQUE INDEX single_university_officer ON accounts (role)
    WHERE status = 'ACTIVE' AND role IN ('RECTOR','ACADEMIC');
CREATE UNIQUE INDEX single_faculty_officer ON accounts (faculty_id)
    WHERE status = 'ACTIVE' AND role = 'FACULTY';
CREATE UNIQUE INDEX single_program_officer ON accounts (program_id)
    WHERE status = 'ACTIVE' AND role = 'PROGRAM';

CREATE TABLE memberships (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id bigint NOT NULL REFERENCES accounts(id),
    program_id bigint NOT NULL REFERENCES programs(id),
    started_at text NOT NULL,
    ended_at text,
    created_by bigint REFERENCES accounts(id),
    ended_by bigint REFERENCES accounts(id)
);
CREATE UNIQUE INDEX active_membership ON memberships (account_id, program_id) WHERE ended_at IS NULL;
CREATE INDEX memberships_by_program ON memberships (program_id, account_id);

CREATE TABLE assignments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id bigint NOT NULL REFERENCES accounts(id),
    role text NOT NULL,
    faculty_id bigint REFERENCES faculties(id),
    program_id bigint REFERENCES programs(id),
    started_at text NOT NULL,
    ended_at text,
    appointed_by bigint NOT NULL REFERENCES accounts(id),
    ended_by bigint REFERENCES accounts(id)
);
CREATE UNIQUE INDEX open_assignment ON assignments (account_id) WHERE ended_at IS NULL;

CREATE TABLE sessions (
    digest text PRIMARY KEY,
    account_id bigint NOT NULL REFERENCES accounts(id),
    expires bigint NOT NULL
);
CREATE INDEX sessions_by_account ON sessions (account_id);

CREATE TABLE verification (
    account_id bigint NOT NULL REFERENCES accounts(id),
    channel text NOT NULL CHECK (channel IN ('email','phone')),
    digest text NOT NULL,
    requested bigint NOT NULL,
    attempts integer NOT NULL DEFAULT 0,
    PRIMARY KEY (account_id, channel)
);

CREATE TABLE notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id bigint NOT NULL REFERENCES accounts(id),
    channel text NOT NULL CHECK (channel IN ('email','phone')),
    destination text NOT NULL,
    code text NOT NULL,
    expires bigint NOT NULL
);

CREATE TABLE rate_limits (
    bucket text PRIMARY KEY,
    started bigint NOT NULL,
    attempts integer NOT NULL
);

